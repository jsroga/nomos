// API response types
export interface RelationshipMatrixResponse {
  nodes: Array<{
    id: string
    name: string
    type: 'character' | 'faction' | 'place' | 'event' | 'rule'
    description?: string
    metadata: {
      role?: string
      archetype?: string
      description?: string
      metrics?: {
        perceivedStakes?: number
        transformation?: number
      }
      [key: string]: unknown
    }
  }>
  edges: Array<{
    source: string
    target: string
    weight: number
    type: string
    label?: string
    /** Textual evidence from LLM extraction */
    evidence?: string
    /** True when grounded by LLM extraction, not purely cosine similarity */
    llmGrounded?: boolean
  }>
  centralCharacter?: string
}
