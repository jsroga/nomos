/**
 * Types for CharacterWeb component
 */

import { Node, Edge } from '@xyflow/react'

export type RelationshipType =
  | 'ally'
  | 'enemy'
  | 'rival'
  | 'mentor'
  | 'student'
  | 'lover'
  | 'family'
  | 'member_of'
  | 'leader_of'
  | 'associated'
  | 'related'
  | 'owns'
  | 'uses'
  | 'caused_by'
  | 'happened_at'
  | 'located_in'
  | 'temporal'
  | 'stranger'
  | 'acquaintance'
  | 'complex'

const RELATIONSHIP_TYPES: RelationshipType[] = [
  'ally',
  'enemy',
  'rival',
  'mentor',
  'student',
  'lover',
  'family',
  'member_of',
  'leader_of',
  'associated',
  'related',
  'owns',
  'uses',
  'caused_by',
  'happened_at',
  'located_in',
  'temporal',
  'stranger',
  'acquaintance',
  'complex',
]

const RELATIONSHIP_TYPE_SET = new Set<string>(RELATIONSHIP_TYPES)

export function parseRelationshipType(value: string | undefined): RelationshipType {
  if (value && RELATIONSHIP_TYPE_SET.has(value)) {
    for (const type of RELATIONSHIP_TYPES) {
      if (type === value) return type
    }
  }
  return 'related'
}

export function readRelationshipEdgeEvidence(
  data: RelationshipEdgeData | undefined
): string | undefined {
  const evidence = data?.evidence
  return typeof evidence === 'string' ? evidence : undefined
}

export function readRelationshipEdgeLlmGrounded(
  data: RelationshipEdgeData | undefined
): boolean | undefined {
  const grounded = data?.llmGrounded
  return typeof grounded === 'boolean' ? grounded : undefined
}

export interface CharacterNodeData {
  [k: string]: unknown
  name: string
  role?: string
  avatarUrl?: string
  description?: string
  type: 'character' | 'faction' | 'place' | 'event' | 'rule'
  // Metrics for visualization
  stressLevel?: number // 0-100
  transformationProgress?: number // 0-100
  // For highlighting
  isHighlighted?: boolean
  isCentral?: boolean
  /** Entity is the focused/navigated-to entity (cyan ring) */
  isSelected?: boolean
}

export interface RelationshipEdgeData {
  [k: string]: unknown
  relationshipType: RelationshipType
  strength: number // 0-1
  trust?: number // -1 to 1
  dynamic?: string
  /** Textual evidence from LLM extraction (story text quote/paraphrase) */
  evidence?: string
  /** True when this edge was generated by the LLM extractor (most accurate) */
  llmGrounded?: boolean
  history?: Array<{
    beatId: string
    change: string
  }>
}

// Node type for React Flow
export type CharacterWebNode = Node<CharacterNodeData>

// Edge type for React Flow
export type CharacterWebEdge = Edge<RelationshipEdgeData>

